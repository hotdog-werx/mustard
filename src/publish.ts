import { setOutput, summary, warning } from '@actions/core';
import type { Names } from './artifacts.ts';
import { formatPercent } from './report.ts';
import type { Annotation, Report } from './report.ts';
import type { Config } from './config.ts';
import { repository, statusCode } from './github.ts';
import type { Event, GitHub } from './github.ts';

type Baseline = { sha: string; runId: number; distance: number };
type Display = {
  report: Report;
  config: Config;
  event: Event;
  baseline?: Baseline;
  configChanged: boolean;
  htmlId?: number;
  reportId?: number;
  outputRunId?: number;
  hasUploads: boolean;
  completeDiff?: boolean;
};

const checkAnnotationBatchSize = 50;

/** Escapes untrusted text for Markdown reports, including characters that can trigger mentions. */
export function escapeMarkdown(value: string): string {
  return value.replace(/\p{Cc}/gu, ' ').replace(/[^\p{L}\p{N} /]/gu, (char) => `&#${char.codePointAt(0)};`);
}

/** Escapes text embedded in generated HTML and SVG. */
export function escapeHtml(value: string): string {
  return value.replace(
    /[&<>"']/g,
    (char) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[char] ?? char,
  );
}

function projectUrl(event: Event) {
  return `${process.env.GITHUB_SERVER_URL ?? 'https://github.com'}/${repository(event.repo)}`;
}

function fileLink(event: Event, path: string, label: string, anchor = '') {
  const repo = event.pull?.head.repo?.full_name ?? repository(event.repo);
  const host = process.env.GITHUB_SERVER_URL ?? 'https://github.com';
  const url = `${host}/${repo}/blob/${event.commit}/${path
    .split('/')
    .map((part) =>
      encodeURIComponent(part).replace(/[!'()*]/g, (value) => `%${value.charCodeAt(0).toString(16)}`),
    )
    .join('/')}${anchor}`;
  return `[${escapeMarkdown(label)}](${url})`;
}

function ranges(numbers: number[]): Array<[number, number]> {
  const groups: Array<[number, number]> = [];
  for (const line of numbers) {
    const last = groups.at(-1);
    if (last && line === last[1] + 1) last[1] = line;
    else groups.push([line, line]);
  }
  return groups;
}

/** Explains the patch result, including a diff that could not be verified. */
function markdownPatch(patch: Report['patch'], completeDiff: boolean, percent: (value: number) => string) {
  if (!completeDiff) return 'The complete patch was unavailable.';
  if (!patch.total) return 'No coverable lines changed.';
  return `**Patch ${percent(patch.percent)}** · ${patch.hit}/${patch.total} fully covered`;
}

/** Renders the totals and context shared by step summaries and PR comments. */
function markdownHeader(
  { report, event, baseline, configChanged, hasUploads, completeDiff = true }: Display,
  showTotals: boolean,
  percent: (value: number) => string,
  delta: (value?: number) => string,
) {
  const sections = ['## Mustard coverage'];
  if (!hasUploads) sections.push('No coverage uploads found for this attempt.');
  if (hasUploads && showTotals) {
    sections.push(`**Project ${percent(report.project.percent)}** · ${delta(report.delta)}`);
    if (event.base) sections.push(markdownPatch(report.patch, completeDiff, percent));
  }
  if (report.incomplete.length) {
    const names = report.incomplete.map((flag) => `**${escapeMarkdown(flag)}**`).join(', ');
    sections.push(
      `> [!WARNING]\n> **Incomplete coverage.** Required flag(s) ${names} did not report. Global coverage only includes the suites that reported. This run does not update the badge or become a baseline.`,
    );
  }
  if (baseline) {
    sections.push(
      `Baseline [${baseline.sha.slice(0, 12)}](${projectUrl(event)}/actions/runs/${baseline.runId})${baseline.distance ? ` · ${baseline.distance} first-parent commit(s) back` : ''}.`,
    );
  } else if (event.base) sections.push('No verified baseline available.');
  if (event.fork) sections.push('Coverage for this fork was generated by the PR code.');
  if (configChanged)
    sections.push('This PR changes coverage configuration. The checks use the merge-base configuration.');
  return sections;
}

/** Links uncovered line ranges to the exact files and revision reviewed. */
function markdownChangedFiles(
  { report, config, event }: Display,
  percent: (value: number) => string,
  delta: (value?: number) => string,
) {
  const rows = report.changed.slice(0, config.comment.maxFiles).map((row) => {
    const groups = ranges(row.uncovered.slice(0, 100));
    const missed = groups
      .slice(0, 12)
      .map(([start, end]) =>
        fileLink(
          event,
          row.path,
          start === end ? String(start) : `${start}–${end}`,
          `#L${start}${start === end ? '' : `-L${end}`}`,
        ),
      )
      .join(', ');
    return `| ${fileLink(event, row.path, row.path)} | ${row.patch ? percent(row.patch.percent) : '—'} | ${delta(row.delta)} | ${missed || '—'}${groups.length > 12 || row.uncovered.length > 100 ? ' …' : ''} |`;
  });
  return [
    '### Changed files',
    '',
    '| File | Patch | Project Δ | Uncovered lines |',
    '| --- | ---: | ---: | --- |',
    ...rows,
    ...(report.changed.length > rows.length
      ? ['', `+${report.changed.length - rows.length} more file(s).`]
      : []),
  ].join('\n');
}

/** Describes where a suite's coverage came from in this report. */
function suiteStatus(flag: string, { report, baseline }: Display) {
  if (report.carried.includes(flag)) return `Carried forward from ${baseline?.sha.slice(0, 12)}`;
  if (report.incomplete.includes(flag)) return '**Missing (required)**';
  if (report.missing.includes(flag)) return 'Missing';
  return 'Uploaded';
}

/** Tabulates each flag's project and patch coverage with its upload status. */
function markdownFlags(display: Display, comment: boolean, percent: (value: number) => string) {
  const { report, config, event } = display;
  const flags = [...report.flagTotals.keys(), ...report.missing].filter(
    (flag) => !(comment && !config.comment.carryforward && report.carried.includes(flag)),
  );
  if (!flags.length) return '';
  const rows = flags.map((flag) => {
    const project = report.flagTotals.get(flag);
    const patch = report.flagPatch.get(flag);
    const patchCell = event.base && patch?.total ? percent(patch.percent) : '—';
    const cells = project
      ? [percent(project.percent), patchCell, `${project.hit}/${project.total}`]
      : ['—', '—', '—'];
    return `| ${escapeMarkdown(flag)} | ${cells.join(' | ')} | ${suiteStatus(flag, display)} |`;
  });
  return [
    '### Flags',
    '',
    '| Flag | Project | Patch | Covered lines | Status |',
    '| --- | ---: | ---: | ---: | --- |',
    ...rows,
  ].join('\n');
}

/** Builds the coverage summary or PR comment, honoring layout settings and size limits. */
export function markdown(display: Display, comment = false): string {
  const { report, config, event, reportId, htmlId, outputRunId } = display;
  const percent = (value: number) => formatPercent(value, config);
  const delta = (value?: number) =>
    value === undefined
      ? '—'
      : `${value > 0 ? '▲ +' : value < 0 ? '▼ −' : ''}${percent(Math.abs(value)).replace('%', ' pp')}`;
  const layout = config.comment.layout;
  const include = (...keys: string[]) => !comment || !layout || keys.some((key) => layout.has(key));
  const sections = markdownHeader(display, include('header', 'reach', 'diff'), percent, delta);
  if (include('flags')) {
    const section = markdownFlags(display, comment, percent);
    if (section) sections.push(section);
  }
  if (report.changed.length && config.comment.maxFiles && include('files', 'diff', 'reach')) {
    sections.push(markdownChangedFiles(display, percent, delta));
  }
  if (config.comment.indirect && report.indirect.length && include('indirect', 'files')) {
    const rows = report.indirect
      .slice(0, config.comment.maxFiles)
      .map((item) => `- ${fileLink(event, item.path, item.path)} · ${delta(item.delta)}`);
    if (report.indirect.length > rows.length)
      rows.push(`- +${report.indirect.length - rows.length} more file(s)`);
    sections.push(['### Indirect changes', '', ...rows].join('\n'));
  }
  if (report.componentTotals.size && include('components')) {
    const rows = [...report.componentTotals.values()].map(
      (item) =>
        `| ${escapeMarkdown(item.name)} | ${percent(item.project.percent)} | ${item.patch.total ? percent(item.patch.percent) : '—'} |`,
    );
    sections.push(
      ['### Components', '', '| Component | Project | Patch |', '| --- | ---: | ---: |', ...rows].join('\n'),
    );
  }
  if (report.checks.length)
    sections.push(
      report.checks
        .map((check) => `- **${escapeMarkdown(check.name)}** · ${check.conclusion} · ${check.message}`)
        .join('\n'),
    );
  const run = `${projectUrl(event)}/actions/runs/${event.runId}`;
  const links = [`[Workflow run](${run})`];
  const outputRun = `${projectUrl(event)}/actions/runs/${outputRunId ?? event.runId}`;
  if (reportId) links.push(`[Coverage data](${outputRun}/artifacts/${reportId})`);
  if (htmlId) links.push(`[HTML report](${outputRun}/artifacts/${htmlId})`);
  return boundedMarkdown(sections, links.join(' · '));
}

/** Keeps complete sections within the Markdown budget and always preserves the footer links. */
function boundedMarkdown(sections: string[], footer: string) {
  const maximum = 48_000;
  const chunks: string[] = [];
  let size = Buffer.byteLength(footer) + 128;
  for (const section of sections) {
    const lines = section.split('\n');
    if (size + Buffer.byteLength(section) > maximum) {
      chunks.push('Some details were omitted because the report reached GitHub’s size limit.');
      break;
    }
    chunks.push(lines.join('\n'));
    size += Buffer.byteLength(section) + 2;
  }
  return [...chunks, footer].join('\n\n');
}

/** Creates a completed check before writing supplementary annotation batches. */
async function publishCheck(
  api: GitHub,
  event: Event,
  {
    name,
    output,
    conclusion,
    annotations,
    details_url,
  }: {
    name: string;
    output: { title: string; summary: string };
    conclusion: Report['checks'][number]['conclusion'];
    annotations: Annotation[];
    details_url: string;
  },
) {
  const chunks = annotationBatches(annotations);
  const first = chunks.shift();
  const { data: run } = await api.rest.checks.create({
    ...event.repo,
    name,
    head_sha: event.commit,
    external_id: `${event.runId}:${event.attempt}:${name}`,
    details_url,
    output: { ...output, annotations: first },
    status: 'completed',
    conclusion,
  });
  for (const [index, batch] of chunks.entries()) {
    try {
      await api.rest.checks.update({
        ...event.repo,
        check_run_id: run.id,
        output: { ...output, annotations: batch },
      });
    } catch (error) {
      if (statusCode(error) !== 404) throw error;
      const remaining = annotations.length - checkAnnotationBatchSize * (index + 1);
      warning(
        `GitHub would not append ${remaining} more annotations to ${name}. See the workflow summary for uncovered lines.`,
      );
      break;
    }
  }
}

/** Publishes each verdict before appending additional line annotations to the patch check. */
export async function writeChecks(api: GitHub, namespace: Names, display: Display) {
  const { event, report } = display;
  for (const check of report.checks) {
    const name = `${namespace.check}/${check.name}`;
    const output = {
      title: check.message,
      summary:
        check.name === 'patch' && report.omittedAnnotations
          ? `${check.message}\n\n+${report.omittedAnnotations} more uncovered line(s).`
          : check.message,
    };
    const annotations = check.name === 'patch' ? report.annotations : [];
    const details_url = `${projectUrl(event)}/actions/runs/${event.runId}`;
    try {
      await publishCheck(api, event, {
        name,
        output,
        conclusion: check.conclusion,
        annotations,
        details_url,
      });
    } catch (error) {
      if (statusCode(error) === 403)
        throw new Error('GitHub refused to write coverage checks. Grant checks: write to this job.', {
          cause: error,
        });
      throw error;
    }
  }
}

/** Splits line annotations into batches that fit the GitHub Checks API limit. */
export function annotationBatches(annotations: Annotation[]): Annotation[][] {
  const result: Annotation[][] = [];
  for (let index = 0; index < annotations.length; index += checkAnnotationBatchSize)
    result.push(annotations.slice(index, index + checkAnnotationBatchSize));
  return result;
}

/** Looks up user tokens through REST and falls back to the GraphQL viewer for GitHub App tokens. */
/** Resolves the identity behind a user or GitHub App token, when GitHub exposes it. */
export async function authenticatedLogin(api: GitHub): Promise<string | undefined> {
  try {
    return (await api.rest.users.getAuthenticated()).data.login;
  } catch {}
  try {
    const result = await api.graphql<{ viewer: { login: string } }>('query { viewer { login } }');
    return result.viewer.login;
  } catch {
    return undefined;
  }
}

/** Finds a marked comment owned by the token’s identity across all pages. */
async function findStickyComment(
  api: GitHub,
  params: Event['repo'] & { issue_number: number },
  namespace: Names,
) {
  let viewer: Promise<string | undefined> | undefined;
  const own = async (login: string | undefined) => {
    if (!login) return false;
    if (login === 'github-actions[bot]') return true;
    // A PAT or GitHub App token posts as another identity. Look it up only when
    // a marked comment from someone else exists, so GITHUB_TOKEN runs stay cheap.
    viewer ??= authenticatedLogin(api);
    return login === (await viewer);
  };
  for await (const { data } of api.paginate.iterator(api.rest.issues.listComments, {
    ...params,
    per_page: 100,
  })) {
    for (const item of data) {
      if (item.body?.split(/\r?\n/, 1)[0] === namespace.marker && (await own(item.user?.login))) {
        return item;
      }
    }
  }
}

/** Applies optional failure-only and coverage-change filters to the PR comment. */
function shouldComment({ report, config, baseline }: Display) {
  const failure = report.checks.some((check) => check.conclusion === 'failure');
  const changed =
    (report.delta !== undefined && report.delta !== 0) ||
    report.changed.some((file) => file.delta !== undefined && file.delta !== 0) ||
    (!baseline && report.patch.total > 0) ||
    report.indirect.length > 0;
  return !(config.comment.failure && !failure) && !(config.comment.changes && !changed);
}

/** Updates or replaces a marked PR comment owned by the posting identity according to repository policy. */
export async function stickyComment(api: GitHub, namespace: Names, display: Display) {
  const { event, config } = display;
  if (!event.pull || config.comment.behavior === 'off' || !shouldComment(display)) return;
  const params = { ...event.repo, issue_number: event.pull.number };
  const body = `${namespace.marker}\n${markdown(display, true)}`;
  try {
    const existing = await findStickyComment(api, params, namespace);
    if (existing) {
      if (config.comment.behavior === 'once' || existing.body === body) return;
      if (config.comment.behavior === 'default') {
        await api.rest.issues.updateComment({ ...event.repo, comment_id: existing.id, body });
        return;
      }
      await api.rest.issues.deleteComment({ ...event.repo, comment_id: existing.id });
    }
    await api.rest.issues.createComment({ ...params, body });
  } catch (error) {
    if (statusCode(error) === 403)
      throw new Error('GitHub refused to write the PR comment. Grant pull-requests: write to this job.', {
        cause: error,
      });
    throw error;
  }
}

/** Writes the workflow summary and exposes the coverage results as action outputs. */
export async function publishSummary(display: Display) {
  await summary.addRaw(markdown(display), true).write();
  const { report, config } = display;
  if (display.hasUploads) setOutput('project-coverage', formatPercent(report.project.percent, config));
  setOutput('project-delta', report.delta === undefined || !display.hasUploads ? '' : report.delta);
  setOutput(
    'patch-coverage',
    display.event.base && display.hasUploads ? formatPercent(report.patch.percent, config) : '',
  );
  setOutput('patch-hits', report.patch.hit);
  setOutput('patch-total', report.patch.total);
  setOutput('baseline-sha', display.baseline?.sha ?? '');
  setOutput('project-status', report.checks.find((check) => check.name === 'project')?.conclusion ?? '');
  setOutput('patch-status', report.checks.find((check) => check.name === 'patch')?.conclusion ?? '');
  setOutput('report-artifact-id', display.reportId ?? '');
  setOutput('missing-required-flags', report.incomplete.join(','));
}

/** Explains which coverage gates failed and whether the merge-base policy affected the result. */
/** Explains which coverage gates failed and whether the merge-base policy affected the result. */
export function failureMessage(
  failed: Report['checks'],
  report: Report,
  prefix: string,
  context: { fromBase: boolean; hasConfig: boolean; configChanged: boolean },
): string {
  const uncovered = report.patch.total - report.patch.hit;
  const lines = report.incomplete.length
    ? [`- Required flag(s) did not report: ${report.incomplete.join(', ')}.`]
    : [];
  lines.push(
    ...failed.map((check) => {
      const detail =
        check.name === 'patch' && uncovered
          ? ` ${uncovered} changed line(s) lack full coverage. See the check's annotations.`
          : '';
      return `- ${prefix}/${check.name}: ${check.message}${detail}`;
    }),
  );
  const hints = [];
  if (context.fromBase && !context.hasConfig)
    hints.push(
      'The merge base has no Mustard config, so the defaults apply (patch target 100%). Policy changes take effect after they reach the base branch.',
    );
  if (context.configChanged)
    hints.push('This PR changes the coverage config, but the checks use the merge-base config.');
  return [
    failed.length
      ? `${failed.length} Mustard coverage check(s) failed, and fail-ci is enabled:`
      : 'Mustard coverage is incomplete, and fail-ci is enabled:',
    ...lines,
    ...hints,
    'The workflow summary has the full report.',
  ].join('\n');
}
